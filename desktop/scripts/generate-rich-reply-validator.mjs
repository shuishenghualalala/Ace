// Compile at development time: the shipped renderer never uses eval/new Function.
import fs from 'node:fs';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
const schema = JSON.parse(fs.readFileSync(new URL('../../crew/sites/rich_reply.schema.json', import.meta.url)));
const ajv = new Ajv({code:{source:true,esm:true},strict:false,allErrors:false});
const code = '/* eslint-disable */\n// Generated by scripts/generate-rich-reply-validator.mjs. Do not edit.\n'+standaloneCode(ajv,ajv.compile(schema));
const destination = new URL('../src/ui/features/rich-reply/validate.generated.js',import.meta.url);
if(process.argv.includes('--check')) {
  if(fs.readFileSync(destination,'utf8')!==code) throw Error('Rich reply validator is stale; regenerate it');
} else fs.writeFileSync(destination,code);
